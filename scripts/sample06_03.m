%[text] ## Setting a separable resampling matrix
%[text] - $\\boldsymbol{M}$: resampling matrix \
%[text] In the separable case
%[text]{"align":"center"} $\\boldsymbol{M}=\\begin{bmatrix} M\_1 & 0 \\\\ 0 & M\_2 \\end{bmatrix}\\in \\mathbb{Z}^{2\\times 2}$
% Vertical downsampling ratio
verticalDFactor = 2;  %[control:slider:8956]{"position":[19,20]}
% Horizontal downsampling ratio
horizontalDFactor = 3;  %[control:slider:8eff]{"position":[21,22]}
%%
%[text] ## Setting an input array
%[text] - $\\mathsf{x}=\\left(x\[\\boldsymbol{m}\]\\right)\_{\\boldsymbol{m}}$: input array (bivariate Gaussian function) \
% Standard deviation
sigma = 2;
% Array size
sizeX = 31;

% Generate an array with the bivariate Gaussian function
arrayX = fspecial('gaussian',sizeX,sigma);
%%
%[text] ## Spectrum of the input array
fig1 = figure;
freqz2(arrayX)
xlabel('\omega_2 (\times\pi rad)')
ylabel('\omega_1 (\times\pi rad)')
title('Before downsampling')
axis ij
%%
%[text] ## Computation of the output array
%[text] - $\\mathsf{y}=\\left(y\[\\boldsymbol{n}\]\\right)\_{\\boldsymbol{n}}$: output array \
%[text]{"align":"center"} $y\[\\boldsymbol{n}\] = x\[\\boldsymbol{M}\\boldsymbol{n}\],\\ \\boldsymbol{n}\\in\\mathbb{Z}^2$
% Definition of the bivariate separable downsampling
downsample2 = @(x,n) ...
    shiftdim(downsample(...
    shiftdim(downsample(x,...
    n(1)),1),...
    n(2)),1);

% Bivariate separable downsampling
arrayY = downsample2(arrayX, [verticalDFactor horizontalDFactor]);
%%
%[text] ## Spectrum of the output array
%[text] The spectrum is stretched and the aliasing components appear (\[M\] Sec. 5.1.1).
fig2 = figure;
freqz2(arrayY)
xlabel('\omega_2 (\times\pi rad)')
ylabel('\omega_1 (\times\pi rad)')
title('After downsampling')
axis ij
%%
%[text] ## Setting a non-separable resampling matrix
%[text] - $\\boldsymbol{M}$: resampling matrix \
%[text] In the general case
%[text]{"align":"center"} $\\boldsymbol{M}=\\begin{bmatrix} \\boldsymbol{m}\_{1} & \\boldsymbol{m}\_{2} \\end{bmatrix}\\in \\mathbb{Z}^{2\\times 2}$
% Resampling matrix
downMtx = [ 1 1 ; -1 1 ];
%%
%[text] ## Setting an input array
% Covariance matrix
covMtx  = [2 0 ; 0 1/2];
% Array size
sizeX = 31;

% Generate an array with the bivariate Gaussian function
arrayX = mygaussian2(sizeX,covMtx);

% Spectrum of x[m]
fig3 = figure;
freqz2(arrayX)
xlabel('\omega_2 (\times\pi rad)')
ylabel('\omega_1 (\times\pi rad)')
title('Before downsampling')
axis ij
%%
%[text] ## Computation of the output array
% Bivariate non-separable downsampling
arrayY = mydownsample2(arrayX,downMtx);

% Spectrum of y[n]
fig4 = figure;
freqz2(arrayY)
xlabel('\omega_2 (\times\pi rad)')
ylabel('\omega_1 (\times\pi rad)')
title('After downsampling')
axis ij
%%
%[text] ## Definitions of local functions
%[text] Generation of a bivariate Gaussian array
function x = mygaussian2(sizeX, covMtx)
% MYGAUSSIAN2 Bivariate Gaussian array
%
% Inputs
%
%   sizeX:  size of the output array (odd number)
%   covMtx: covariance matrix
%
% Output
%
%   x: array generated by the Gaussian function (sum is 1)
%
sizeHalf = floor(sizeX / 2);

if isscalar(covMtx)
    covMtx = covMtx * eye(2);
end

x = zeros(2*sizeHalf+1);
iRow = 1;
for n1 = -sizeHalf:sizeHalf
    iCol = 1;
    for n0 = -sizeHalf:sizeHalf
        p = - 0.5 * [ n0 n1 ] * (covMtx\[ n0 n1 ].');
        x(iRow,iCol) = exp(p);
        iCol = iCol + 1;
    end
    iRow = iRow + 1;
end
x = x / sum(x,"all");

end % of mygaussian2
%[text] Bivariate non-separable downsampling
function [outputArray, X, Y] = mydownsample2(inputArray,downMtx,phase)
% MYDOWNSAMPLE2 Bivariate downsampling with a resampling matrix
%
% Inputs
%
%   inputArray: input array
%   downMtx:    resampling matrix
%   phase:      downsampling phase
%
% Outputs
%
%   outputArray: output array
%   X          : horizontal sampling points
%   Y          : vertical sampling points
%
if nargin < 3
    phase = [0 0].';
else
    phase = phase(:);
end

% Size of the input array
nRowsInputArray = size(inputArray,1);
nColsInputArray = size(inputArray,2);
nCompInputArray = size(inputArray,3);

% Support region after downsampling
vertexPoints(:,1) = [ 0 0 ].';
vertexPoints(:,2) = downMtx \ [ 0 nColsInputArray-1 ].';
vertexPoints(:,3) = downMtx \ [ nRowsInputArray-1 0 ].';
vertexPoints(:,4) = downMtx \ [ nRowsInputArray-1 nColsInputArray-1 ].';
minPoint = floor(min(vertexPoints,[],2));
maxPoint = ceil(max(vertexPoints,[],2));

% Shift the downsampling phase into FPD(downMtx)
phase = phase - downMtx * floor(downMtx \ phase);

% Downsampling
outputArray = zeros(maxPoint(1)-minPoint(1)+1, maxPoint(2)-minPoint(2)+1, ...
    nCompInputArray, 'like', inputArray);
iRow = 1;
for m0 = minPoint(1):maxPoint(1)
    iCol = 1;
    for m1 = minPoint(2):maxPoint(2)
        originalPoint = downMtx * [ m0 m1 ].';
        n0 = originalPoint(1) + phase(1);
        n1 = originalPoint(2) + phase(2);
        if n0 >= 0 && n0 < nRowsInputArray  && ...
                n1 >= 0 && n1< nColsInputArray
            outputArray(iRow, iCol, :) = inputArray(n0 + 1, n1 + 1, :);
        end
        iCol = iCol + 1;
    end
    iRow = iRow + 1;
end

Y = minPoint(1):maxPoint(1);
X = minPoint(2):maxPoint(2);

end % of mydownsample2

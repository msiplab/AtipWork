%[text] ## Online manual
%[text] `help` prints the help text in the Command Window, `doc` opens the documentation,
%[text] and `lookfor` searches the first help lines for a keyword.
%[text] Check what `i`, `j` and `pi` are.  The reference text uses $\\mathrm{j}$ for the imaginary unit.
help i
help j
help pi

function filename = savetex(name,content)
%SAVETEX Write a LaTeX snippet for the slides to the results folder
%
%   FILENAME = ATIP.SAVETEX(NAME,CONTENT) saves the string CONTENT as
%   results/NAME.tex in UTF-8 and returns the path.
%
%   Numbers computed in the live scripts (matrices, tables, answers of
%   numerical examples) reach the slides without being copied by hand.
%   tools/sync-results.ps1 of AtipSlides copies results/atip-*.tex to
%   AtipSlides/snippets/, and the slides read them with \atipsnippet{NAME}.
%
%   NAME should have the form "atip-NN-..." (NN = lecture number).
%
%   Example:
%       X = [1 2; 3 4];
%       atip.savetex("atip-04-example", "\begin{pmatrix}" + atip.arr2tex(X) + "\end{pmatrix}")
%
%   See also ATIP.ARR2TEX, ATIP.FMTINT, ATIP.PRJFOLDERS
%
% Copyright (c) Shogo MURAMATSU, 2026
% All rights reserved.
%
arguments
    name (1,1) string
    content (1,1) string
end

[~,resfolder] = atip.prjfolders();
filename = fullfile(resfolder, name + ".tex");
header = "% " + name + ".tex --- generated by an AtipWork live script. Do not edit." + newline;
fid = fopen(filename,"w","n","UTF-8");
cleaner = onCleanup(@() fclose(fid));
fprintf(fid,"%s%s%%\n",header,content);
end
